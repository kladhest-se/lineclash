#!/usr/bin/env sh
# Release metadata shared by make and packaging. No source files are mutated
# except when the explicit `header PATH` operation is requested.
set -eu
root=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
version=${VERSION:-$(sed -n 's/^VERSION[[:space:]]*?*=[[:space:]]*//p' "$root/version.mk" | head -1)}
number=${BUILD_NUMBER:-$(printf '%s\n' "$version" | awk -F. '{print $1*10000+$2*100+$3}')}
case "$number" in ''|*[!0-9]*) echo 'BUILD_NUMBER must be numeric' >&2; exit 1;; esac
if [ -n "${SOURCE_DATE_EPOCH:-}" ]; then
    build_date=$(date -u -r "$SOURCE_DATE_EPOCH" +%Y-%m-%d 2>/dev/null || date -u -d "@$SOURCE_DATE_EPOCH" +%Y-%m-%d)
else
    build_date=$(date -u +%Y-%m-%d)
fi
case "${1:-version}" in
    version) printf '%s\n' "$version" ;;
    num|buildnum) printf '%s\n' "$number" ;;
    date) printf '%s\n' "$build_date" ;;
    header)
        target=$2
        tmp=$(mktemp "${target}.XXXXXX")
        trap 'rm -f "$tmp"' EXIT HUP INT TERM
        printf '/* generated by get-version.sh */\n#define BUILD_NUMBER %s\n#define BUILD_DATE "%s"\n' "$number" "$build_date" > "$tmp"
        if ! cmp -s "$tmp" "$target"; then mv "$tmp" "$target"; fi
        ;;
    *) echo 'Usage: get-version.sh [version|num|buildnum|date|header PATH]' >&2; exit 1 ;;
esac
