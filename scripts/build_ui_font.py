#!/usr/bin/env python3
"""Bake the bundled OFL Roboto font into a dependency-free antialiased SDL atlas.
Requires Pillow only when deliberately regenerating the checked-in header.
"""
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
import hashlib
root=Path(__file__).resolve().parents[1]
path=root/'clients/gui/third_party/fonts/Roboto.ttf'
font=ImageFont.truetype(str(path),56)
axes=font.get_variation_axes();font.set_variation_by_axes([500 if a['name']==b'Weight' else a['default'] for a in axes])
extra=[0x2013,0x2014,0x2018,0x2019,0x201c,0x201d,0x2022,0x2026,0x2190,0x2191,0x2192,0x2193,0x25b6,0x25c0,0x2605,0x2713,0x2715,0x2264]
points=list(range(256))+extra
w,h=2048,720
atlas=Image.new('L',(w,h));draw=ImageDraw.Draw(atlas);metrics=[]
for i,cp in enumerate(points):
    ch=chr(cp) if cp>=32 and not 127<=cp<160 else '?'
    left,top,right,bottom=font.getbbox(ch,anchor='ls')
    x=(i%32)*64;y=(i//32)*72
    draw.text((x-left,y-top),ch,font=font,fill=255,anchor='ls')
    metrics.append((x,y,max(0,right-left),max(0,bottom-top),left,top,round(font.getlength(ch)*64)))
raw=atlas.tobytes();rle=[];last=raw[0];count=0
for value in raw:
    if value!=last or count==255:rle.extend((count,last));count=0;last=value
    count+=1
rle.extend((count,last))
header='/* Generated by scripts/build_ui_font.py. Roboto: SIL OFL 1.1; see docs/licenses/Roboto-OFL.txt. */\n'
header+='#define UI_ATLAS_W 2048\n#define UI_ATLAS_H 720\n'
header+='static const unsigned int UI_EXTRA[]={'+','.join(map(str,extra))+'};\n'
header+='static const int UI_GLYPHS[][7]={\n'+''.join('{'+','.join(map(str,m))+'},\n' for m in metrics)+'};\n'
header+='static const unsigned char UI_FONT_RLE[]={\n'+''.join(','.join(map(str,rle[i:i+64]))+',\n' for i in range(0,len(rle),64))+'};\n'
(root/'clients/gui/src/ui_font.h').write_text(header)
print('Baked Roboto atlas:',len(rle),'bytes, font SHA256',hashlib.sha256(path.read_bytes()).hexdigest())
